import test from 'node:test';
import assert from 'node:assert/strict';
import { RateChart } from '../ui/rate-chart.mjs';

test('rapid pointer input uses its latest position and pending hover stops when hidden or detached', t => {
  const previous = Object.fromEntries(['document', 'requestAnimationFrame', 'cancelAnimationFrame'].map(key => [key, globalThis[key]]));
  t.after(() => { for (const [key, value] of Object.entries(previous)) {
    if (value === undefined) delete globalThis[key]; else globalThis[key] = value;
  } });
  const frames = new Map();
  let id = 0, rendered = 0;
  globalThis.document = { visibilityState: 'visible' };
  globalThis.requestAnimationFrame = callback => { frames.set(++id, callback); return id; };
  globalThis.cancelAnimationFrame = frame => frames.delete(frame);
  const plot = new EventTarget();
  plot.closest = () => null;
  plot.getBoundingClientRect = () => ({ left: 0, width: 400 });
  const tooltip = { hidden: true };
  const host = new EventTarget();
  host.isConnected = true;
  host.querySelector = selector => selector === '.agent-curve' ? plot : tooltip;
  const chart = new RateChart();
  chart.host = host;
  chart.geometry = { width: 400 };
  chart.timeline.update('thread', [0, 1000, 2000].map(time => ({ time: new Date(time).toISOString(), measuredTps: 2, estimatedTps: 0 })));
  chart.drawOverlay = () => { rendered++; };
  chart.bind();
  const move = clientX => plot.dispatchEvent(Object.assign(new Event('pointermove'), { clientX }));
  const flush = () => { for (const [frame, callback] of frames) { frames.delete(frame); callback(); } };
  move(100); move(200); move(300);
  assert.equal(frames.size, 1);
  flush();
  assert.equal(rendered, 1);
  assert.equal(chart.timeline.cursor, (300 - 38) / 354 * 2000);
  move(200);
  chart.suspend();
  assert.equal(frames.size, 0);
  assert.equal(tooltip.hidden, true);
  move(200);
  document.visibilityState = 'hidden';
  flush();
  assert.equal(rendered, 1);
  document.visibilityState = 'visible';
  move(100);
  chart.detach();
  assert.equal(frames.size, 0);
  move(300);
  assert.equal(frames.size, 0);
});

test('range controls keep the displayed data range during loading and recover after failure independently', async () => {
  const create = () => {
    const plot = new EventTarget();
    plot.closest = () => null;
    const host = new EventTarget();
    const select = { value: '5', disabled: false }, loading = { hidden: true, textContent: '' };
    host.querySelector = selector => selector === '.curve-window' ? select : selector === '.curve-loading' ? loading : plot;
    const chart = new RateChart();
    chart.host = host;
    chart.timeline.update('thread', [0, 1000, 2000].map(time => ({ time: new Date(time).toISOString(), measuredTps: 2, estimatedTps: 0 })));
    chart.bind();
    return { chart, host, plot, select, loading };
  };
  const global = create(), thread = create();
  let requested, finish;
  global.chart.onWindowChange = minutes => { requested = minutes; return new Promise(resolve => { finish = resolve; }); };
  const change = () => {
    const event = new Event('change');
    Object.defineProperty(event, 'target', { value: { matches: selector => selector === '.curve-window', value: '60' } });
    global.host.dispatchEvent(event);
  };
  change();
  assert.equal(requested, 60);
  assert.equal(global.select.value, '5');
  assert.equal(global.select.disabled, true);
  assert.equal(global.loading.textContent, '加载 60 min');
  assert.equal(thread.chart.windowMinutes, 5);
  finish(false);
  await Promise.resolve();
  assert.equal(global.select.value, '5');
  assert.equal(global.select.disabled, false);
  assert.equal(global.loading.hidden, true);
  change();
  global.chart.windowMinutes = 60;
  finish(true);
  await Promise.resolve();
  assert.equal(global.select.value, '60');
  assert.equal(thread.select.value, '5');
  const before = [...global.chart.timeline.view];
  const zoom = Object.assign(new Event('keydown', { cancelable: true }), { key: '+' });
  global.plot.dispatchEvent(zoom);
  assert.equal(zoom.defaultPrevented, false);
  assert.deepEqual(global.chart.timeline.view, before);
  global.chart.detach(); thread.chart.detach();
});
